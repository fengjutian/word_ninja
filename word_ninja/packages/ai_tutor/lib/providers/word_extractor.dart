List<String> _extractWords(String text) {
  final matches =
      RegExp(r'[a-zA-Z]{4,}(?:-[a-zA-Z]+)*').allMatches(text.toLowerCase());
  final seen = <String>{};
  final words = <String>[];
  for (final m in matches) {
    final w = m.group(0)!;
    if (!_stopWords.contains(w) && seen.add(w)) {
      words.add(w);
    }
  }
  return words;
}
